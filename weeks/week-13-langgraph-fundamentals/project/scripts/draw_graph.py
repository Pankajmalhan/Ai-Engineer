"""Write the compiled graph's topology to graph.md as a Mermaid diagram (no API key needed).
Open graph.md in VS Code's markdown preview to see it rendered.

    uv run python scripts/draw_graph.py
"""

from __future__ import annotations

import os
import sys

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
sys.path.insert(0, ROOT)

from langchain_core.language_models.fake_chat_models import FakeListChatModel
from langgraph.checkpoint.memory import MemorySaver

from app.graph import build_graph

# The topology doesn't depend on the model, so a fake one avoids needing credentials.
graph = build_graph(FakeListChatModel(responses=["unused"]), checkpointer=MemorySaver())
mermaid = graph.get_graph().draw_mermaid()

out_path = os.path.join(ROOT, "graph.md")
with open(out_path, "w") as f:
    f.write(f"# Week 13 graph\n\nGenerated by `scripts/draw_graph.py` -- do not edit by hand.\n\n```mermaid\n{mermaid}```\n")
print(f"wrote {out_path}")
